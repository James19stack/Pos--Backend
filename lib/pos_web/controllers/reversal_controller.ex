defmodule PosWeb.ReversalController do
  use PosWeb, :controller
  use OpenApiSpex.ControllerSpecs

  alias OpenApiSpex.Schema
  alias Pos.{Repo, Reversals, Sales}
  alias PosWeb.{ApiJSON, Schemas}

  action_fallback PosWeb.FallbackController
  plug OpenApiSpex.Plug.CastAndValidate, json_render_error_v2: true
  plug PosWeb.Plugs.RequireRole, :supervisor when action in [:list_returns]
  tags ["Voids and returns"]

  @id_param [id: [in: :path, description: "Sale id", schema: %Schema{type: :string, format: :uuid}]]

  operation :lookup,
    summary: "Find a sale by its receipt number",
    description: "For returns: any cashier can look a sale up. The reply says how much of each line can still be returned.",
    parameters: [receipt_no: [in: :path, description: "Printed on the receipt, e.g. R5B7C8F0E", type: :string]],
    responses: %{200 => {"Sale", "application/json", Schemas.GenericResponse}, 404 => {"Not found", "application/json", Schemas.Error}}

  def lookup(conn, %{receipt_no: receipt_no}) do
    case Sales.get_sale_by_receipt(receipt_no) do
      nil -> {:error, :not_found}
      sale -> json(conn, %{data: ApiJSON.sale_for_return(sale, Reversals.remaining(sale))})
    end
  end

  operation :void,
    summary: "Void a cash sale",
    description: """
    Cancels a cash-only sale from a shift that is still open and puts the stock back.
    A cashier needs a supervisor's `approver_email` and `approver_password`; supervisors and
    above need nothing extra. A reason is required. Card or M-Pesa sales, and sales from closed
    shifts, must be returned instead.
    """,
    parameters: @id_param,
    request_body: {"Reason and approval", "application/json", Schemas.VoidRequest},
    responses: %{
      200 => {"Voided", "application/json", Schemas.GenericResponse},
      422 => {"Not allowed", "application/json", Schemas.Error}
    }

  def void(conn, %{id: id}) do
    with {:ok, sale} <- Reversals.void_sale(conn.assigns.current_user, id, conn.body_params) do
      json(conn, %{data: ApiJSON.sale(Repo.preload(sale, [:items, :payments]))})
    end
  end

  operation :create_return,
    summary: "Return items from a sale",
    description: """
    Refunds some or all items of a completed sale. `id` is generated by the till, so a retry
    returns the original return (200) and never refunds twice. The refund comes out of YOUR open
    shift's drawer (`refund_method: cash`); use `other` when the money goes back outside the
    system, such as an M-Pesa reversal. Same approval rule as voids.
    """,
    parameters: @id_param,
    request_body: {"Items to return", "application/json", Schemas.ReturnRequest},
    responses: %{
      200 => {"Already recorded", "application/json", Schemas.GenericResponse},
      201 => {"Recorded", "application/json", Schemas.GenericResponse},
      422 => {"Not allowed", "application/json", Schemas.Error}
    }

  def create_return(conn, %{id: sale_id}) do
    body = conn.body_params
    existed? = Reversals.get_return(body.id) != nil

    with {:ok, return} <- Reversals.return_items(conn.assigns.current_user, sale_id, body) do
      conn |> put_status(if existed?, do: :ok, else: :created) |> json(%{data: ApiJSON.return(return)})
    end
  end

  operation :list_returns,
    summary: "Returns made against a sale",
    description: "Supervisors and above.",
    parameters: @id_param,
    responses: %{200 => {"Returns", "application/json", Schemas.GenericResponse}}

  def list_returns(conn, %{id: id}), do: json(conn, %{data: Enum.map(Reversals.list_returns(id), &ApiJSON.return/1)})
end
