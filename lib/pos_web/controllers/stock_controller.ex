defmodule PosWeb.StockController do
  use PosWeb, :controller
  use OpenApiSpex.ControllerSpecs

  alias Pos.{Catalog, Inventory, Repo}
  alias PosWeb.{ApiJSON, ErrorResponse, Schemas}

  action_fallback PosWeb.FallbackController
  plug OpenApiSpex.Plug.CastAndValidate, json_render_error_v2: true
  plug PosWeb.Plugs.RequireRole, :supervisor
  tags ["Stock"]

  @reasons %{"adjustment" => :adjustment, "wastage" => :wastage, "expiry" => :expiry}

  operation :create_receipt,
    summary: "Receive a delivery",
    description: """
    Posts goods received: stock goes up and each product's cost is updated (audited).
    `id` is generated by the client, so repeating the call returns the original receipt (200)
    and never adds the stock twice. Each item names a product by `barcode` or `sku`.
    """,
    request_body: {"Delivery", "application/json", Schemas.GoodsReceiptRequest},
    responses: %{
      200 => {"Already posted", "application/json", Schemas.GenericResponse},
      201 => {"Posted", "application/json", Schemas.GenericResponse},
      422 => {"Invalid", "application/json", Schemas.Error}
    }

  def create_receipt(conn, _params) do
    body = conn.body_params
    existed? = Inventory.get_receipt(body.id) != nil

    with {:ok, receipt} <- Inventory.receive_goods(conn.assigns.current_user, body) do
      conn
      |> put_status(if existed?, do: :ok, else: :created)
      |> json(%{data: ApiJSON.goods_receipt(receipt)})
    end
  end

  operation :adjust,
    summary: "Record wastage, expiry or a stock correction",
    description: """
    A note is required. Wastage and expiry always remove stock. A general `adjustment`
    (+ found, - lost) is for managers only; supervisors can record wastage and expiry.
    Everything is audited.
    """,
    request_body: {"Adjustment", "application/json", Schemas.AdjustmentRequest},
    responses: %{
      201 => {"Recorded", "application/json", Schemas.GenericResponse},
      403 => {"Managers only", "application/json", Schemas.Error},
      422 => {"Invalid", "application/json", Schemas.Error}
    }

  def adjust(conn, _params) do
    body = conn.body_params
    user = conn.assigns.current_user

    if body.reason == "adjustment" and user.role == :supervisor do
      ErrorResponse.respond(conn, 403, "forbidden", "Only managers can make general stock adjustments. Supervisors can record wastage and expiry.")
    else
      with %{} = product <- find(body) || {:error, :not_found},
           {:ok, result} <- Inventory.record_adjustment(user, product.id, body.quantity, @reasons[body.reason], body.note) do
        conn
        |> put_status(:created)
        |> json(%{data: %{product_id: product.id, movement: ApiJSON.movement(result.movement), stock_quantity: ApiJSON.dec(result.quantity)}})
      end
    end
  end

  operation :low,
    summary: "Products to reorder",
    description: "Active products at or below their reorder level, lowest first, including ones never stocked.",
    responses: %{200 => {"Low stock", "application/json", Schemas.GenericResponse}}

  def low(conn, _params) do
    rows = for {product, qty} <- Inventory.low_stock(), do: %{product: ApiJSON.product_admin(product), quantity: ApiJSON.dec(qty)}
    json(conn, %{data: rows})
  end

  defp find(%{barcode: code}) when is_binary(code), do: Catalog.get_product_by_barcode(code)
  defp find(%{sku: sku}) when is_binary(sku), do: Repo.get_by(Pos.Catalog.Product, sku: sku, active: true)
  defp find(_), do: nil
end
